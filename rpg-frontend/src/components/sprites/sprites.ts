export function getSpriteForName(name: string): SpriteData {
  const n = name.toLowerCase()
  if (n.includes('witch'))                           return WITCH
  if (n.includes('dragon'))                          return DRAGON
  if (n.includes('spider'))                          return GIANT_SPIDER
  if (n.includes('goblin') && n.includes('mage'))    return GOBLIN_MAGE
  if (n.includes('goblin'))                          return GOBLIN_WARRIOR
  return GOBLIN_WARRIOR
}